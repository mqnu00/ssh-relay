#!/usr/bin/env bash
# Create the release signing key and the keystore.properties that Gradle reads.
#
#   scripts/make-keystore.sh                          # prompts for a password
#   KEYSTORE_PASSWORD=... scripts/make-keystore.sh    # non-interactive (CI)
#
# Optional overrides: KEYSTORE, ALIAS, DN, VALIDITY_DAYS
#
# Both outputs are gitignored. Back them up somewhere safe and offline: an Android
# app can only ever be updated with the same signing key, so losing it means you can
# never ship an update to an installed app again (on Play, losing the *upload* key is
# recoverable if you enrolled in Play App Signing; losing the app signing key is not).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=../env.sh
source "$ROOT/env.sh" >/dev/null

# Kept under .toolchain/ by default: it is already gitignored and keeps every build
# input workspace-local, which is how the rest of this project is set up.
KEYSTORE="${KEYSTORE:-$SSHRELAY_TOOLCHAIN/keystore/release.jks}"
PROPS="$ROOT/keystore.properties"
ALIAS="${ALIAS:-sshrelay}"
DN="${DN:-CN=SSH Relay, O=mqnu00, C=CN}"
VALIDITY_DAYS="${VALIDITY_DAYS:-10000}"

KEYTOOL="$JAVA_HOME/bin/keytool"
[ -x "$KEYTOOL" ] || { echo "keytool not found; run: python3 scripts/provision.py" >&2; exit 1; }

if [ -f "$KEYSTORE" ]; then
  echo "a keystore already exists at $KEYSTORE" >&2
  echo "delete it first if you really want to replace it (existing installs would" >&2
  echo "no longer be upgradable with the new key)" >&2
  exit 1
fi

PASSWORD="${KEYSTORE_PASSWORD:-}"
if [ -z "$PASSWORD" ]; then
  printf 'password for the new keystore: '
  read -rs PASSWORD
  printf '\nrepeat: '
  read -rs AGAIN
  printf '\n'
  [ "$PASSWORD" = "$AGAIN" ] || { echo "passwords did not match" >&2; exit 1; }
fi
if [ "${#PASSWORD}" -lt 6 ]; then
  echo "keytool requires at least 6 characters" >&2
  exit 1
fi

mkdir -p "$(dirname "$KEYSTORE")"
# PKCS12 uses one password for both the store and the key, which is what every
# modern toolchain expects; RSA 4096 with a long validity is the safe default.
"$KEYTOOL" -genkeypair \
  -keystore "$KEYSTORE" \
  -storetype PKCS12 \
  -alias "$ALIAS" \
  -keyalg RSA -keysize 4096 \
  -validity "$VALIDITY_DAYS" \
  -storepass "$PASSWORD" \
  -keypass "$PASSWORD" \
  -dname "$DN" >/dev/null

# Paths in keystore.properties are resolved against the repository root.
case "$KEYSTORE" in
  "$ROOT"/*) STORE_FILE="${KEYSTORE#"$ROOT"/}" ;;
  *)         STORE_FILE="$KEYSTORE" ;;
esac

umask 077
cat >"$PROPS" <<EOF
# Generated by scripts/make-keystore.sh -- gitignored, do not commit.
storeFile=$STORE_FILE
storePassword=$PASSWORD
keyAlias=$ALIAS
keyPassword=$PASSWORD
EOF
chmod 600 "$PROPS" "$KEYSTORE" 2>/dev/null || true

echo
echo "keystore : $KEYSTORE"
echo "props    : $PROPS"
echo "alias    : $ALIAS"
echo "SHA-256  : $("$JAVA_HOME/bin/keytool" -list -v -keystore "$KEYSTORE" -storepass "$PASSWORD" -alias "$ALIAS" 2>/dev/null | awk -F': ' '/SHA256:/{print $2; exit}')"
echo
echo "next: ./gradlew :app:assembleRelease   -> signed app-release.apk"
echo "      ./gradlew :app:bundleRelease     -> signed app-release.aab (Play)"
echo
echo "Back up both files now. Without this key you cannot update an installed app."
